"""
Retail Loyalty & Promo Performance -- Streamlit dashboard
=========================================================
A portfolio dashboard built around the kind of work an Enterprise Analytics
team does day-to-day: track retail KPIs, measure a promo A/B test, segment
customers with RFM, and validate the underlying data like a dbt test suite.

ALL DATA IS SYNTHETIC (generated by data_gen.py from a fixed seed).

Run:
    pip install -r requirements.txt
    streamlit run app.py

Author: Leo Chan -- github.com/GoldenCrate
"""

from __future__ import annotations

import altair as alt
import pandas as pd
import streamlit as st

import data_gen
import analytics

# --------------------------------------------------------------------------- #
# Storytelling-with-Data palette: one grey for context, one accent for signal.
# Restrained on purpose -- color is used to point, not to decorate.
# --------------------------------------------------------------------------- #
INK = "#2B2B2B"       # text / primary bars
GREY = "#BFBFBF"      # context / de-emphasized
ACCENT = "#C2410C"    # single accent (terracotta) for the one thing that matters
ACCENT_2 = "#0F766E"  # secondary accent, used sparingly (treatment group)
GOOD = "#15803D"
BAD = "#B91C1C"

st.set_page_config(page_title="Retail Loyalty & Promo Performance",
                   page_icon="chart", layout="wide")


# --------------------------------------------------------------------------- #
# Data loading (cached). Regenerated deterministically in-memory, so the app
# works on a fresh clone with no pre-built CSVs.
# --------------------------------------------------------------------------- #
@st.cache_data(show_spinner=False)
def load_data():
    tables = data_gen.generate_all()
    return tables


def money(x: float) -> str:
    return f"${x:,.0f}"


# Shared Altair theme tweaks: declutter (no gridlines, light axes).
def base_chart(df: pd.DataFrame) -> alt.Chart:
    return alt.Chart(df).configure_view(stroke=None).configure_axis(
        grid=False, domainColor=GREY, tickColor=GREY, labelColor=INK, titleColor=INK
    )


def takeaway(text: str) -> None:
    """The 'so what' line -- one sentence that states the insight for every view."""
    st.markdown(
        f"<div style='background:#FFF7ED;border-left:4px solid {ACCENT};"
        f"padding:0.6rem 0.9rem;border-radius:4px;margin:0.4rem 0 1.0rem 0;'>"
        f"<b>So what:</b> {text}</div>",
        unsafe_allow_html=True,
    )


# --------------------------------------------------------------------------- #
# Load
# --------------------------------------------------------------------------- #
tables = load_data()
orders = tables["orders"]
kpis = analytics.compute_kpis(orders)

st.title("Retail Loyalty & Promo Performance")
st.caption(
    "Synthetic demonstration dashboard - no real customer or sales data. "
    "Built by Leo Chan (github.com/GoldenCrate) as a portfolio piece."
)

view = st.sidebar.radio(
    "View",
    ["KPI Overview", "Promo A/B Lift", "RFM Segmentation", "Data Quality"],
)
st.sidebar.markdown("---")
st.sidebar.markdown(
    f"**Dataset (synthetic)**\n\n"
    f"- {len(orders):,} orders\n"
    f"- {kpis['customers']:,} customers\n"
    f"- {orders['store_id'].nunique()} stores\n"
    f"- 12 months of history\n\n"
    f"Fixed seed = {data_gen.SEED}, so every run matches."
)


# =========================================================================== #
# VIEW 1 -- KPI OVERVIEW
# =========================================================================== #
if view == "KPI Overview":
    st.subheader("Headline retail KPIs (trailing 12 months)")

    c1, c2, c3, c4, c5 = st.columns(5)
    c1.metric("Revenue", money(kpis["revenue"]))
    c2.metric("Orders", f"{kpis['orders']:,}")
    c3.metric("Avg order value", f"${kpis['aov']:,.2f}")
    c4.metric("Loyalty % of sales", f"{kpis['loyalty_share']:.0%}")
    c5.metric("Promo % of sales", f"{kpis['promo_share']:.0%}")

    takeaway(
        f"Loyalty members drive <b>{kpis['loyalty_share']:.0%}</b> of revenue while being "
        f"a minority of the file - the loyalty program is the single biggest lever on sales."
    )

    # Monthly revenue trend, loyalty vs non-loyalty, directly labeled.
    trend = analytics.revenue_by_month(orders)
    # Drop the first and last partial months so the trend isn't misread.
    full_months = sorted(trend["month"].unique())[1:-1]
    trend = trend[trend["month"].isin(full_months)]

    color = alt.Color(
        "segment:N",
        scale=alt.Scale(domain=["Loyalty", "Non-loyalty"], range=[ACCENT, GREY]),
        legend=None,
    )
    line = (
        alt.Chart(trend)
        .mark_line(point=False, strokeWidth=3)
        .encode(
            x=alt.X("month:T", title=None),
            y=alt.Y("revenue:Q", title="Monthly revenue ($)",
                    axis=alt.Axis(format="$,.0s")),
            color=color,
        )
    )
    # Direct labels at the right end instead of a legend.
    last = trend[trend["month"] == trend["month"].max()]
    labels = (
        alt.Chart(last)
        .mark_text(align="left", dx=6, fontWeight="bold")
        .encode(
            x=alt.X("month:T"),
            y=alt.Y("revenue:Q"),
            text="segment:N",
            color=color,
        )
    )
    chart = (line + labels).properties(
        height=340,
        title=alt.TitleParams(
            "Loyalty revenue holds steady and leads non-loyalty every month",
            anchor="start", fontSize=16, color=INK,
        ),
    ).configure_view(stroke=None).configure_axis(
        grid=False, domainColor=GREY, tickColor=GREY, labelColor=INK, titleColor=INK
    )
    st.altair_chart(chart, width='stretch')

    # Revenue by store, sorted, single accent on the top store.
    by_store = (
        orders.merge(tables["stores"], on="store_id")
        .groupby("store_name", as_index=False)["revenue"].sum()
        .sort_values("revenue", ascending=False)
    )
    top_store = by_store.iloc[0]["store_name"]
    by_store["hl"] = by_store["store_name"].eq(top_store)
    bars = (
        alt.Chart(by_store)
        .mark_bar()
        .encode(
            x=alt.X("revenue:Q", title="Revenue ($)", axis=alt.Axis(format="$,.0s")),
            y=alt.Y("store_name:N", sort="-x", title=None),
            color=alt.condition(alt.datum.hl, alt.value(ACCENT), alt.value(GREY)),
            tooltip=[alt.Tooltip("store_name:N", title="Store"),
                     alt.Tooltip("revenue:Q", title="Revenue", format="$,.0f")],
        )
        .properties(
            height=300,
            title=alt.TitleParams(
                f"{top_store} leads the fleet on revenue",
                anchor="start", fontSize=16, color=INK,
            ),
        )
        .configure_view(stroke=None)
        .configure_axis(grid=False, domainColor=GREY, tickColor=GREY,
                        labelColor=INK, titleColor=INK)
    )
    st.altair_chart(bars, width='stretch')


# =========================================================================== #
# VIEW 2 -- PROMO A/B LIFT
# =========================================================================== #
elif view == "Promo A/B Lift":
    st.subheader('A/B test: "Loyalty 15% Off Weekend" email vs. holdout')

    ab = analytics.ab_two_proportion(tables["experiment"])

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Control conversion", f"{ab.rate_control:.2%}",
              help=f"{ab.conv_control:,} of {ab.n_control:,} held-out customers")
    c2.metric("Treatment conversion", f"{ab.rate_treatment:.2%}",
              help=f"{ab.conv_treatment:,} of {ab.n_treatment:,} emailed customers")
    c3.metric("Absolute lift", f"{ab.abs_lift:+.2%}")
    c4.metric("Relative lift", f"{ab.rel_lift:+.1%}")

    verdict = "statistically significant" if ab.significant else "not statistically significant"
    vcolor = GOOD if ab.significant else BAD
    st.markdown(
        f"Two-proportion z-test: <b>z = {ab.z_stat:.2f}</b>, "
        f"<b>p = {ab.p_value:.4f}</b> &rarr; "
        f"<span style='color:{vcolor};font-weight:700'>{verdict}</span> at &alpha; = 0.05. "
        f"95% CI on the absolute lift: "
        f"<b>[{ab.ci_low:+.2%}, {ab.ci_high:+.2%}]</b>.",
        unsafe_allow_html=True,
    )

    takeaway(
        f"The promo lifted conversion from {ab.rate_control:.1%} to {ab.rate_treatment:.1%} "
        f"(a <b>{ab.rel_lift:+.0%}</b> relative gain, p = {ab.p_value:.3f}) - the campaign "
        f"worked and is worth rolling out, with the CI excluding zero."
    )

    # Conversion-rate bars with 95% CI error bars; treatment in accent.
    rate_df = pd.DataFrame({
        "group": ["Control (holdout)", "Treatment (emailed)"],
        "rate": [ab.rate_control, ab.rate_treatment],
    })
    # Per-group Wald CI for the error bars.
    import math
    def wald(p, n):
        se = math.sqrt(p * (1 - p) / n)
        return p - 1.96 * se, p + 1.96 * se
    lo_c, hi_c = wald(ab.rate_control, ab.n_control)
    lo_t, hi_t = wald(ab.rate_treatment, ab.n_treatment)
    rate_df["lo"] = [lo_c, lo_t]
    rate_df["hi"] = [hi_c, hi_t]

    base = alt.Chart(rate_df)
    bars = base.mark_bar(size=80).encode(
        x=alt.X("group:N", title=None, axis=alt.Axis(labelAngle=0)),
        y=alt.Y("rate:Q", title="Conversion rate", axis=alt.Axis(format=".0%")),
        color=alt.condition(alt.datum.group == "Treatment (emailed)",
                            alt.value(ACCENT_2), alt.value(GREY)),
    )
    err = base.mark_errorbar().encode(
        x="group:N",
        y=alt.Y("lo:Q", title=""),
        y2="hi:Q",
    )
    text = base.mark_text(dy=-8, fontWeight="bold", color=INK).encode(
        x="group:N", y="rate:Q", text=alt.Text("rate:Q", format=".1%"),
    )
    chart = (bars + err + text).properties(
        height=360,
        title=alt.TitleParams(
            f"Emailed group converts {ab.rel_lift:+.0%} higher - and the gap is real",
            anchor="start", fontSize=16, color=INK,
        ),
    ).configure_view(stroke=None).configure_axis(
        grid=False, domainColor=GREY, tickColor=GREY, labelColor=INK, titleColor=INK
    )
    st.altair_chart(chart, width='stretch')

    with st.expander("How this test is computed"):
        st.markdown(
            "- **Design:** whole-base holdout. Every customer was randomized to "
            "receive the promo email (treatment) or be held out (control).\n"
            "- **Metric:** share of customers who made a qualifying purchase in the window.\n"
            "- **Test:** two-proportion z-test. Pooled standard error for the "
            "z-statistic / p-value; unpooled SE for the 95% CI on the difference.\n"
            "- **Decision rule:** ship if the CI on lift excludes zero at alpha = 0.05."
        )


# =========================================================================== #
# VIEW 3 -- RFM SEGMENTATION
# =========================================================================== #
elif view == "RFM Segmentation":
    st.subheader("RFM customer segmentation")

    rfm = analytics.compute_rfm(orders, data_gen.SNAPSHOT_DATE)
    summary = analytics.segment_summary(rfm)

    champ = summary[summary["segment"] == "Champions"]
    champ_rev = float(champ["pct_revenue"].iloc[0]) if len(champ) else 0.0
    champ_cust = float(champ["pct_customers"].iloc[0]) if len(champ) else 0.0

    takeaway(
        f"<b>Champions</b> are just {champ_cust:.0%} of customers but "
        f"{champ_rev:.0%} of revenue; <b>At-Risk</b> and <b>Can't-Lose-Them</b> "
        f"segments are the priority list for win-back spend."
    )

    # Highlight Champions in accent; everyone else grey. Sorted by revenue.
    summary = summary.sort_values("total_monetary", ascending=False)
    summary["hl"] = summary["segment"].eq("Champions")
    bars = (
        alt.Chart(summary)
        .mark_bar()
        .encode(
            x=alt.X("total_monetary:Q", title="Revenue ($)",
                    axis=alt.Axis(format="$,.0s")),
            y=alt.Y("segment:N", sort="-x", title=None),
            color=alt.condition(alt.datum.hl, alt.value(ACCENT), alt.value(GREY)),
            tooltip=[
                alt.Tooltip("segment:N", title="Segment"),
                alt.Tooltip("customers:Q", title="Customers", format=","),
                alt.Tooltip("total_monetary:Q", title="Revenue", format="$,.0f"),
                alt.Tooltip("pct_revenue:Q", title="% of revenue", format=".1%"),
                alt.Tooltip("avg_frequency:Q", title="Avg orders", format=".1f"),
                alt.Tooltip("avg_recency_days:Q", title="Avg days since order", format=".0f"),
            ],
        )
        .properties(
            height=340,
            title=alt.TitleParams(
                "A few Champions carry most of the revenue",
                anchor="start", fontSize=16, color=INK,
            ),
        )
        .configure_view(stroke=None)
        .configure_axis(grid=False, domainColor=GREY, tickColor=GREY,
                        labelColor=INK, titleColor=INK)
    )
    st.altair_chart(bars, width='stretch')

    st.markdown("**Segment detail**")
    show = summary.drop(columns=["hl"]).copy()
    show = show.rename(columns={
        "segment": "Segment", "customers": "Customers",
        "avg_recency_days": "Avg recency (days)", "avg_frequency": "Avg frequency",
        "total_monetary": "Revenue", "pct_customers": "% customers",
        "pct_revenue": "% revenue",
    })
    st.dataframe(
        show.style.format({
            "Customers": "{:,.0f}",
            "Avg recency (days)": "{:.0f}",
            "Avg frequency": "{:.1f}",
            "Revenue": "${:,.0f}",
            "% customers": "{:.1%}",
            "% revenue": "{:.1%}",
        }),
        width='stretch', hide_index=True,
    )

    with st.expander("How segments are built"):
        st.markdown(
            "- **Recency** = days since last order (lower is better).\n"
            "- **Frequency** = number of orders. **Monetary** = total revenue.\n"
            "- Each dimension is scored 1-5 by quintile; F and M are averaged "
            "into a combined FM score.\n"
            "- An (R, FM) grid maps every customer to a named segment "
            "(Champions, Loyal, At Risk, Can't Lose Them, Hibernating, ...)."
        )


# =========================================================================== #
# VIEW 4 -- DATA QUALITY
# =========================================================================== #
elif view == "Data Quality":
    st.subheader("Data-quality validation (dbt-style test suite)")

    checks = analytics.run_data_quality(tables)
    n_pass = sum(c.status == "pass" for c in checks)
    n_total = len(checks)

    c1, c2, c3 = st.columns(3)
    c1.metric("Tests run", n_total)
    c2.metric("Passed", n_pass)
    c3.metric("Failed", n_total - n_pass)

    all_pass = n_pass == n_total
    if all_pass:
        st.success(f"All {n_total} data-quality tests passed - the dataset is safe to analyze.")
    else:
        st.error(f"{n_total - n_pass} test(s) failed - investigate before trusting the numbers.")

    takeaway(
        "Before any KPI or A/B number ships, the pipeline runs not-null, "
        "uniqueness, accepted-range, accepted-values and referential-integrity "
        "tests - the same contract a dbt project enforces in CI."
    )

    rows = [{
        "Test": c.test,
        "Applies to": c.target,
        "Result": "pass" if c.status == "pass" else "FAIL",
        "Detail": c.detail,
    } for c in checks]
    qdf = pd.DataFrame(rows)

    def style_result(val):
        color = GOOD if val == "pass" else BAD
        return f"color: {color}; font-weight: 700"

    st.dataframe(
        qdf.style.map(style_result, subset=["Result"]),
        width='stretch', hide_index=True,
    )

    st.markdown(
        "**What each test type means**\n"
        "- `not_null` - required columns are never empty.\n"
        "- `unique` - primary keys have no duplicates.\n"
        "- `accepted_range` - revenue is always positive.\n"
        "- `accepted_values` - categorical columns only hold expected labels.\n"
        "- `relationships` - every foreign key resolves to a parent row "
        "(referential integrity)."
    )

st.sidebar.markdown("---")
st.sidebar.caption("Synthetic data - portfolio demo only. (c) Leo Chan")
